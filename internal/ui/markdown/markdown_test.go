func TestImagesFindsOnlyBlockImages(t *testing.T) {
	tests := []struct {
		name, body string
		want       []string
	}{
		{"image inside text", "see ![a](x.png) here", nil},
		{"list item", "- ![a](x.png)", nil},
		{"blockquote", "> ![a](x.png)", nil},
		{"table cell", "| h |\n|---|\n| ![a](x.png) |", nil},
		{"html img block", "<img src=x.png>", nil},
		{"html img inside text", "para <img src=x.png>", nil},
		{"raw html after the image", "![a](x.png)<br>", nil},
		{"link-wrapped image", "[![a](x.png)](https://e)", []string{"x.png"}},
		{"deduplicated in first-seen order", "![a](x.png) ![b](y.png)\n\n![c](x.png)", []string{"x.png", "y.png"}},
		{"soft break keeps both", "![a](x.png)\n![b](y.png)", []string{"x.png", "y.png"}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := Images(tt.body)
			if tt.want == nil && got != nil {
				t.Fatalf("Images = %q, want nil", got)
			}
			if !slices.Equal(got, tt.want) {
				t.Fatalf("Images = %q, want %q", got, tt.want)
			}
		})
	}
}

func TestRenderWithImagesSplicesBlockImage(t *testing.T) {
	const body = "intro\n\n![shot](/attachments/x.png)\n\noutro"
	if got := Images(body); !slices.Equal(got, []string{"/attachments/x.png"}) {
		t.Fatalf("Images = %q", got)
	}
	blocks := map[string][]string{"/attachments/x.png": {"ROW0", "ROW1"}}
	got := RenderWithImages(body, 40, blocks)
	if !strings.Contains(got, "ROW0\nROW1") {
		t.Fatalf("spliced rows are not consecutive lines:\n%s", strip(got))
	}
	lines := strings.Split(strip(got), "\n")
	for i := range lines {
		lines[i] = strings.TrimSpace(lines[i])
	}
	i := slices.Index(lines, "ROW0")
	if i < 2 || i+3 >= len(lines) {
		t.Fatalf("spliced rows sit at line %d of %d:\n%s", i, len(lines), strip(got))
	}
	if lines[i-2] != "intro" || lines[i-1] != "" || lines[i+2] != "" || lines[i+3] != "outro" {
		t.Errorf("neighbours of the spliced rows are wrong:\n%s", strip(got))
	}
	if strings.Contains(strip(got), "shot") {
		t.Errorf("the link line survived the splice:\n%s", strip(got))
	}
}

