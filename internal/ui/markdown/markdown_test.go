func TestRenderNeverDropsWordsWhenWrapping(t *testing.T) {
	// Tables are left out: they change shape with width by design, so their words move.
	body := "# A heading that is long enough to wrap\n\nSome **bold** and _italic_ prose with a [link text](https://example.com/a/long/path) and `code spans` too.\n\n" +
		"- first item that wraps around the edge of a narrow pane\n  - nested item that also wraps around the edge\n- [ ] a task item that wraps around\n\n" +
		"> quoted words that wrap around the edge of a narrow pane\n\n```\na long line of code that has to be hard wrapped somewhere\n```\n"
	alnum := func(s string) string {
		return strings.Map(func(r rune) rune {
			if unicode.IsLetter(r) || unicode.IsDigit(r) {
				return r
			}
			return -1
		}, strip(s))
	}
	want := alnum(Render(body, 1000))
	for _, w := range []int{20, 30, 60, 80} {
		if got := alnum(Render(body, w)); got != want {
			t.Errorf("width %d lost or reordered text:\n got %q\nwant %q", w, got, want)
		}
	}
}

